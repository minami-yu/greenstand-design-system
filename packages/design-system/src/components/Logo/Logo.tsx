export function Logo({
  accessibilityLabel,
  name = 'greenstand',
  size = 'md',
  style,
  variant,
  ...props
}: LogoProps) {
  const resolvedLabel = accessibilityLabel ?? (name === 'treetracker' ? 'Treetracker' : 'Greenstand');

  if (name === 'treetracker') {
    const resolvedVariant = resolveTreetrackerVariant(variant);
    const colors = treetrackerColors[resolvedVariant];
    const height = treetrackerHeights[size];

    return (
      <View
        {...props}
        accessibilityLabel={resolvedLabel}
        accessibilityRole="image"
        style={[styles.treetrackerRoot, { height, width: height * 4.8 }, style]}
      >
        <Svg height={height * 0.73} viewBox="0 0 232 36.2935" width={height * 4.65}>
          {TREETRACKER_PATHS.map((path) => (
            <Path
              d={path.d}
              fill={path.part === 'mark' ? colors.mark : colors.text}
              key={path.d}
            />
          ))}
        </Svg>
      </View>
    );
  }

  const resolvedVariant = resolveGreenstandVariant(variant);
  const dimension = greenstandSizes[size];

  return (
    <View
      {...props}
      accessibilityLabel={resolvedLabel}
      accessibilityRole="image"
      style={[styles.greenstandRoot, { height: dimension, width: dimension }, style]}
    >
      <GreenstandMark color={greenstandColors[resolvedVariant]} height={dimension * 0.84} />
    </View>
  );
}

function GreenstandMark({ color, height }: { color: string; height: number }) {
  return (
    <Svg
      height={height}
      viewBox="0 0 31.8944 40"
      width={height * 0.79736}
    >
      {GREENSTAND_PATHS.map((path) => (
        <Path d={path} fill={color} key={path} />
      ))}
    </Svg>
  );
}

function resolveGreenstandVariant(variant?: LogoVariant): GreenstandLogoVariant {
  if (variant === 'neutral' || variant === 'original' || variant === 'white') {
    return variant;
  }

  return 'default';
}

function resolveTreetrackerVariant(variant?: LogoVariant): TreetrackerLogoVariant {
  return variant === 'white' ? 'white' : 'default';
}

