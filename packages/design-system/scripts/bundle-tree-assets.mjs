import { readFileSync, writeFileSync } from 'node:fs';
// Preserve the Figma SVGs verbatim in modules consumable by Metro and Vite.
for (const [component, names] of Object.entries({
  TreeTag: ['md', 'lg', 'xl'],
  SimpleTreeTag: ['default', 'small', 'focus', 'treeIcon'],
  CurrentLocationTag: ['cone', 'dot']
})) {
  const base = new URL(`../src/components/${component}/assets/`, import.meta.url);
  const assets = Object.fromEntries(names.map(name => [name, readFileSync(new URL(`${name}.svg`, base), 'utf8')]));
  writeFileSync(new URL('svgAssets.ts', base), '// GENERATED by scripts/bundle-tree-assets.mjs; do not edit.\nexport const svgAssets = ' + JSON.stringify(assets, null, 2) + ' as const;\n');
}
