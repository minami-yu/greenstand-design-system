import { readFileSync, writeFileSync } from 'node:fs';

// Preserve downloaded Figma artwork for both Metro and Vite.
const base = new URL('../src/components/Hint/assets/', import.meta.url);
const assets = Object.fromEntries(['tap', 'pointer'].map(name => [name, readFileSync(new URL(`${name}.svg`, base), 'utf8')]));
writeFileSync(new URL('svgAssets.ts', base), '// GENERATED by scripts/bundle-hint-assets.mjs; do not edit.\nexport const svgAssets = ' + JSON.stringify(assets, null, 2) + ' as const;\n');
